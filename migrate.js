// Migrácia databázy: vytvorí a upraví tabuľky, doplní predvolené nastavenia a údaje pre novú prevádzku.
// Spúšťa sa samostatne pred štartom servera – lokálne `npm run migrate`, na serveri ju volá deploy.sh.
// Dá sa spustiť opakovane, existujúce dáta nemení.
import crypto from 'node:crypto';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { db } from './db.js';
import { hashPassword } from './passwords.js';

// dátumy a časy rezervácií sú text (YYYY-MM-DD, HH:MM) v lokálnom čase prevádzky
await db.exec(`
  -- procedúry v jednej miestnosti sa nesmú časovo prekrývať
  CREATE TABLE IF NOT EXISTS rooms (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text    NOT NULL
  );

  CREATE TABLE IF NOT EXISTS procedures (
    id           integer          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text             NOT NULL,
    description  text             NOT NULL DEFAULT '',
    duration_min integer          NOT NULL,
    price        double precision NOT NULL,
    icon         text             NOT NULL DEFAULT 'hand',
    active       integer          NOT NULL DEFAULT 1,
    sort         integer          NOT NULL DEFAULT 0,
    room_id      integer          REFERENCES rooms(id) ON DELETE SET NULL
  );

  -- členovia tímu: zobrazujú sa na webe a majú vlastný kalendár rezervácií
  CREATE TABLE IF NOT EXISTS team_members (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text    NOT NULL,
    title  text    NOT NULL DEFAULT '',
    photo  text    NOT NULL DEFAULT '',
    active integer NOT NULL DEFAULT 1,
    sort   integer NOT NULL DEFAULT 0
  );
  -- bio = text „o mne“ v profile na webe (vypĺňa admin alebo terapeut sám)
  ALTER TABLE team_members ADD COLUMN IF NOT EXISTS bio text NOT NULL DEFAULT '';

  CREATE TABLE IF NOT EXISTS procedure_members (
    procedure_id integer NOT NULL REFERENCES procedures(id) ON DELETE CASCADE,
    member_id    integer NOT NULL REFERENCES team_members(id) ON DELETE CASCADE,
    PRIMARY KEY (procedure_id, member_id)
  );

  -- role: admin vidí všetko, solver len rezervácie svojho člena tímu;
  -- profil (meno, telefón, fotka) sa pri napojení na člena tímu berie z tímu
  CREATE TABLE IF NOT EXISTS users (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text        NOT NULL,
    password_hash text        NOT NULL,
    role          text        NOT NULL CHECK (role IN ('admin', 'solver')),
    member_id     integer     REFERENCES team_members(id) ON DELETE SET NULL,
    email         text        NOT NULL DEFAULT '',
    name          text        NOT NULL DEFAULT '',
    phone         text        NOT NULL DEFAULT '',
    photo         text        NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now()
  );
  CREATE UNIQUE INDEX IF NOT EXISTS users_username ON users (lower(username));

  -- odkazy na nastavenie hesla (ukladá sa len hash tokenu);
  -- invite = prvé nastavenie hesla nového účtu, reset = neskôr poslaný odkaz
  CREATE TABLE IF NOT EXISTS password_tokens (
    token_hash text    PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at bigint  NOT NULL,
    kind       text    NOT NULL DEFAULT 'reset'
  );

  -- prihlásenia do adminu (ukladá sa len hash tokenu z cookie), prežijú reštart servera
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash text    PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at bigint  NOT NULL
  );

  -- účty klientov z verejného webu (oddelené od účtov administrácie);
  -- gdpr_consent_at = kedy klient pri registrácii udelil súhlas so spracúvaním osobných údajov,
  -- verified_at = kedy potvrdil e-mail (NULL = nepotvrdený, nedá sa prihlásiť)
  CREATE TABLE IF NOT EXISTS clients (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text        NOT NULL,
    password_hash   text        NOT NULL,
    name            text        NOT NULL,
    phone           text        NOT NULL DEFAULT '',
    gdpr_consent_at timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    verified_at     timestamptz
  );
  CREATE UNIQUE INDEX IF NOT EXISTS clients_email ON clients (lower(email));

  CREATE TABLE IF NOT EXISTS client_sessions (
    token_hash text    PRIMARY KEY,
    client_id  integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    expires_at bigint  NOT NULL
  );

  -- odkazy na potvrdenie e-mailu po registrácii (ukladá sa len hash tokenu)
  CREATE TABLE IF NOT EXISTS client_tokens (
    token_hash text    PRIMARY KEY,
    client_id  integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    expires_at bigint  NOT NULL
  );

  -- jednorazové odkazy na nastavenie nového hesla klienta (zabudnuté heslo)
  CREATE TABLE IF NOT EXISTS client_password_tokens (
    token_hash text    PRIMARY KEY,
    client_id  integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    expires_at bigint  NOT NULL
  );

  -- názov, trvanie a cena procedúry sa kopírujú, aby rezervácia ostala správna aj po úprave cenníka;
  -- client_id = rezervácia prihláseného klienta, cancel_reason = dôvod, keď ju klient zrušil na webe
  CREATE TABLE IF NOT EXISTS bookings (
    id             integer          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id   integer          REFERENCES procedures(id) ON DELETE SET NULL,
    procedure_name text             NOT NULL,
    duration_min   integer          NOT NULL,
    price          double precision NOT NULL,
    date           text             NOT NULL,
    time           text             NOT NULL,
    end_time       text             NOT NULL,
    name           text             NOT NULL,
    phone          text             NOT NULL,
    email          text             NOT NULL DEFAULT '',
    note           text             NOT NULL DEFAULT '',
    status         text             NOT NULL DEFAULT 'new',
    created_at     timestamptz      NOT NULL DEFAULT now(),
    room_id        integer          REFERENCES rooms(id) ON DELETE SET NULL,
    member_id      integer          REFERENCES team_members(id) ON DELETE SET NULL,
    member_name    text             NOT NULL DEFAULT '',
    client_id      integer          REFERENCES clients(id) ON DELETE SET NULL,
    cancel_reason  text             NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS bookings_date ON bookings (date, time);
  CREATE INDEX IF NOT EXISTS bookings_member ON bookings (member_id, date);
  CREATE INDEX IF NOT EXISTS bookings_client ON bookings (client_id);

  CREATE TABLE IF NOT EXISTS settings (
    key   text PRIMARY KEY,
    value text NOT NULL
  );

  -- každý pokus o odoslanie SMS (kind: confirmed = potvrdenie termínu, test = testovacia z adminu);
  -- status: sent | error, delivery = posledný zistený stav doručenia zo SMSfarm
  CREATE TABLE IF NOT EXISTS sms_log (
    id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    kind       text        NOT NULL,
    booking_id integer     REFERENCES bookings(id) ON DELETE SET NULL,
    phone      text        NOT NULL,
    recipient  text        NOT NULL DEFAULT '',
    message    text        NOT NULL,
    status     text        NOT NULL,
    request_id text        NOT NULL DEFAULT '',
    error      text        NOT NULL DEFAULT '',
    delivery   text        NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS sms_log_created ON sms_log (created_at);

  -- fotky tímu a profilov (JPEG); name sa ukladá do team_members.photo a users.photo, web ich dáva na /media/<name>
  CREATE TABLE IF NOT EXISTS media (
    name       text        PRIMARY KEY,
    data       bytea       NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
  );
`);

// ---------- fotky, ktoré sa kedysi ukladali na disk (DATA_DIR/media) ----------

// súbory na disku ostávajú ako záloha, prenesú sa len tie, ktoré ešte v databáze nie sú
const mediaDir = path.join(process.env.DATA_DIR || path.join(import.meta.dirname, 'data'), 'media');
if (existsSync(mediaDir)) {
  for (const name of readdirSync(mediaDir).filter((f) => f.endsWith('.jpg'))) {
    const { changes } = await db.run('INSERT INTO media (name, data) VALUES (?, ?) ON CONFLICT (name) DO NOTHING',
      name, readFileSync(path.join(mediaDir, name)));
    if (changes) console.log(`Fotka prenesená do databázy: ${name}`);
  }
}

// ---------- predvolené údaje pre úplne novú prevádzku ----------

// kľúče hodín: 0 = nedeľa … 6 = sobota, null = zatvorené
const DEFAULT_SETTINGS = {
  hours: {
    0: null,
    1: ['07:00', '20:00'],
    2: ['07:00', '20:00'],
    3: ['07:00', '20:00'],
    4: ['07:00', '20:00'],
    5: ['07:00', '20:00'],
    6: ['08:00', '13:00'],
  },
  slot_step: 30,
  max_days_ahead: 60,
  blocked_dates: [],
  // kontakt do e-mailov a na web; prvé hodnoty sa prevezmú z .env, potom sa menia v administrácii
  contact_phone: process.env.CONTACT_PHONE || '',
  site_url: process.env.SITE_URL || '',
  address: '',
  // id používateľov, na ktorých e-maily chodia notifikácie pre tím (prázdne = ADMIN_EMAIL z .env)
  notify_user_ids: [],
  // SMSfarm.sk – zadáva admin v Nastaveniach (heslo sa do prehliadača neposiela)
  sms_integration_id: '',
  sms_integration_code: '',
  sms_sender: '',
  // vypínač SMS notifikácií – false = cez SMS bránu sa neposiela nič (okrem ručnej testovacej SMS)
  sms_enabled: true,
};

for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
  await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING', key, JSON.stringify(value));
}

if (!(await db.get('SELECT 1 FROM rooms LIMIT 1')) && !(await db.get('SELECT 1 FROM procedures LIMIT 1'))) {
  await db.tx(async (t) => {
    const { id: roomId } = await t.run("INSERT INTO rooms (name) VALUES ('Miestnosť 1') RETURNING id");
    const procedures = [
      ['Vstupné vyšetrenie', 'Kineziologický rozbor, diagnostika pohybového aparátu a návrh terapie.', 60, 45, 'pulse'],
      ['Terapia chrbtice', 'Krčná, hrudná aj drieková chrbtica, hernie disku a blokády.', 50, 45, 'spine'],
      ['Športová rehabilitácia', 'Bezpečný návrat k výkonu po zraneniach väzov, svalov a šliach.', 50, 50, 'sport'],
      ['Manuálna terapia', 'Mäkké techniky, mobilizácie a uvoľnenie spúšťových bodov.', 30, 30, 'hand'],
      ['Rázová vlna', 'Pätová ostroha, tenisový lakeť, kalcifikáty a chronické bolesti šliach.', 20, 35, 'bolt'],
      ['Detská fyzioterapia', 'Vojtova metóda, skolióza a správne držanie tela u detí.', 45, 40, 'child'],
    ];
    for (const [i, p] of procedures.entries()) {
      await t.run(
        'INSERT INTO procedures (name, description, duration_min, price, icon, sort, room_id) VALUES (?, ?, ?, ?, ?, ?, ?)',
        ...p, i, roomId
      );
    }
    if (!(await t.get('SELECT 1 FROM team_members LIMIT 1'))) {
      const team = [
        ['Mgr. Peter Novák', 'Vedúci fyzioterapeut'],
        ['Mgr. Jana Kováčová', 'Športová fyzioterapia'],
        ['Bc. Martin Horák', 'Manuálna terapia'],
        ['Mgr. Lucia Malá', 'Detská fyzioterapia'],
      ];
      for (const [i, m] of team.entries()) await t.run('INSERT INTO team_members (name, title, sort) VALUES (?, ?, ?)', ...m, i);
    }
  });
}

// Prvý účet: admin s heslom z ADMIN_PASSWORD (ďalšie účty sa zakladajú v administrácii)
if (!(await db.get('SELECT 1 FROM users LIMIT 1'))) {
  let password = process.env.ADMIN_PASSWORD;
  if (!password) {
    password = crypto.randomBytes(9).toString('base64url');
    console.warn(`ADMIN_PASSWORD nie je nastavené – dočasné heslo pre účet „admin“: ${password}`);
  }
  await db.run("INSERT INTO users (username, password_hash, role) VALUES ('admin', ?, 'admin')", hashPassword(password));
  console.log('Vytvorený účet „admin“ (heslo z ADMIN_PASSWORD).');
}

await db.close();
console.log('Migrácia dokončená.');
