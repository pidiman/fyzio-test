// poradie kvôli cudzím kľúčom
const TABLES = [
  'rooms', 'procedures', 'team_members', 'procedure_members', 'users', 'password_tokens', 'sessions',
  'clients', 'client_sessions', 'client_tokens', 'bookings', 'settings',
];

async function importSqlite(file) {
  const src = new DatabaseSync(file, { readOnly: true });
  await db.tx(async (t) => {
    // časy v SQLite sú v UTC bez časovej zóny
    await t.exec("SET LOCAL TIME ZONE 'UTC'");
    for (const table of TABLES) {
      const srcCols = src.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
      if (!srcCols.length) continue;
      const dstCols = (await t.all('SELECT column_name FROM information_schema.columns WHERE table_name = ?', table))
        .map((c) => c.column_name);
      const cols = srcCols.filter((c) => dstCols.includes(c));
      const insert = `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(() => '?').join(', ')})`;
      const rows = src.prepare(`SELECT ${cols.join(', ')} FROM ${table}`).all();
      for (const row of rows) await t.run(insert, ...cols.map((c) => row[c]));
      // účty klientov z čias pred overovaním e-mailu sa považujú za potvrdené
      if (table === 'clients' && !srcCols.includes('verified_at')) {
        await t.run('UPDATE clients SET verified_at = created_at');
      }
      // ďalšie id pokračuje za prenesenými
      if (dstCols.includes('id')) {
        await t.exec(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM ${table}`);
      }
      console.log(`Prenesené z SQLite: ${table} (${rows.length})`);
    }
  });
  src.close();
  // pôvodný súbor ostane ako záloha, ďalší štart ho už neprenáša
  for (const suffix of ['', '-wal', '-shm']) {
    if (existsSync(file + suffix)) renameSync(file + suffix, `${file}.migrated${suffix}`);
  }
}

